import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { once } from "node:events";
import { createInterface } from "node:readline";
import pg from "pg";
import { postgresConfig } from "../lib/postgres-config.ts";

let url=process.env.DATABASE_URL;
if (!url) {
  const stdin=createInterface({input:process.stdin});
  const [line]=await once(stdin,"line");
  stdin.close();
  url=line.trim();
}
if (!url) throw new Error("Missing DATABASE_URL");
process.env.DATABASE_URL=url;
const {all,bookVolunteer,campaign,campaignImpact,campaigns,cancelVolunteer,confirmCash,contribute,expenses,manage,needs,publicExpensePhoto,publicUpdatePhoto,publicVolunteerCalendar,recordExpense,transaction,updates,volunteerShifts}=await import("../lib/db.ts");
const {assistMatches,parseAssist}=await import("../lib/assist.ts");
const [rows,items,posts,shifts]=await Promise.all([
  campaigns(),needs(),updates("lop-hoc-sau-mua"),volunteerShifts("lop-hoc-sau-mua"),
]);
assert.ok(rows.length>=3 && typeof rows[0].received==="number");
assert.ok(items.some(item=>item.topic==="learning" && typeof item.pledged==="number"));
assert.ok(posts.length && typeof posts[0].hasPhoto==="number");
assert.ok(shifts.length && typeof shifts[0].startsAt==="string");

const pool=new pg.Pool(postgresConfig(url));
const session=await pool.connect();
try {
  await session.query("BEGIN");
  const found=await session.query("insert into gopsuc.limits (key,count,until) values ($1,1,0) returning count",["deployment-check"]);
  assert.equal(found.rows[0].count,1);
  const roles=await session.query("select has_schema_privilege('anon','gopsuc','USAGE') as anon, has_column_privilege('anon','gopsuc.receipts','action_hash','SELECT') as anon_hash, has_table_privilege('anon','gopsuc.expense_photos','SELECT') as anon_photo, has_table_privilege('anon','gopsuc.request_replays','SELECT') as anon_replay, current_user as role");
  assert.equal(roles.rows[0].anon,false);
  assert.equal(roles.rows[0].anon_hash,false);
  assert.equal(roles.rows[0].anon_photo,false);
  assert.equal(roles.rows[0].anon_replay,false);
  assert.equal(roles.rows[0].role,"gopsuc_runtime");
  console.log("PostgreSQL: read models, runtime writes, and private schema verified.");
} finally {
  await session.query("ROLLBACK");
  session.release();
  await pool.end();
}
const rollback = new Error("discard validation fixtures");
await assert.rejects(transaction(async()=>{
  const slug="kiem-tra-trien-khai";
  const draft={title:"Test",description:"Test",category:"Giáo dục",location:"Huế",cover:"school",goal:50_000};
  await manage("organizer",slug,"create",draft);
  await manage("organizer",slug,"editDraft",{...draft,title:"Updated"});
  await manage("admin",slug,"publish",{});
  const cashData={slug,kind:"cash",amount:25000};
  const cashKey=randomBytes(32).toString("hex");
  const {gift:cash,actionToken:cashToken}=await contribute(cashData,cashKey);
  const replayCash=await contribute(cashData,cashKey);
  assert.equal(replayCash.gift.code,cash.code);
  assert.equal(replayCash.actionToken,cashToken);
  await assert.rejects(contribute({...cashData,amount:26000},cashKey),/khác nội dung/);
  await assert.rejects(confirmCash(cash.code),/liên kết thao tác riêng/);
  assert.equal((await confirmCash(cash.code,cashToken)).duplicate,false);
  assert.equal((await confirmCash(cash.code,cashToken)).duplicate,true);
  assert.equal((await campaign(slug)).received,25000);
  await manage("organizer",slug,"need",{name:"Dụng cụ",unit:"bộ",target:5,handoff:"Điểm demo",topic:"learning"});
  const [item]=await needs(slug);
  const {gift:goods}=await contribute({slug,kind:"goods",amount:5,needId:item.id});
  await assert.rejects(contribute({slug,kind:"goods",amount:1,needId:item.id}), /vượt quá/);
  await manage("organizer",slug,"receive",{code:goods.code,actual:4});
  assert.equal((await needs(slug))[0].received,4);
  const bytes=Buffer.from("binary persistence check");
  await manage("organizer",slug,"update",{title:"Test photo",body:"Test report",image:""},bytes);
  const [post]=await updates(slug);
  assert.deepEqual(await publicUpdatePhoto(slug,post.id),bytes);
  const local=new Date(Date.now()+48*3600_000).toISOString().slice(0,16);
  await manage("organizer",slug,"addShift",{title:"Test shift",location:"Demo",startLocal:local,capacity:1});
  const [shift]=await volunteerShifts(slug);
  const event=await publicVolunteerCalendar(slug,shift.id);
  assert.equal(event.startsAt,shift.startsAt);
  assert.equal(await publicVolunteerCalendar("bep-am-cuoi-tuan",shift.id),undefined);
  const intent=parseAssist("Mình có 15 bộ dụng cụ học tập ở Huế, muốn tình nguyện hoặc góp 20k",["Huế"]);
  const live=assistMatches(intent.filters,[(await campaign(slug))],await needs(slug),[shift]);
  assert.equal(live.goods[0].suggested,1);
  assert.equal(live.volunteer[0].available,1);
  assert.equal(live.cash[0].amount,20000);
  const impact=await campaignImpact(slug);
  assert.equal(impact.received,25000);
  assert.deepEqual(impact.updates.map(update=>update.title),["Test photo"]);
  const shiftKey=randomBytes(32).toString("hex");
  const {booking,actionToken:bookingToken}=await bookVolunteer(slug,shift.id,shiftKey);
  assert.equal(booking.shiftId,shift.id);
  assert.equal((await bookVolunteer(slug,shift.id,shiftKey)).booking.code,booking.code);
  await assert.rejects(bookVolunteer(slug,shift.id),/đủ người/);
  await assert.rejects(cancelVolunteer(booking.code,cashToken),/liên kết thao tác riêng/);
  assert.equal((await cancelVolunteer(booking.code,bookingToken)).status,"cancelled");
  await all("INSERT INTO sessions VALUES(?,?,?)","deployment-check","admin",0);
  await all("DELETE FROM sessions WHERE token=?","deployment-check");
  const cost={title:"Test",amount:25000,evidence:"Demo"};
  const costKey=randomBytes(32).toString("hex");
  await recordExpense("admin",slug,cost,bytes,costKey);
  await recordExpense("admin",slug,cost,bytes,costKey);
  assert.equal((await campaign(slug)).spent,25000);
  assert.equal((await expenses(slug)).length,1);
  const [charge]=await expenses(slug);
  assert.match(charge.photo_sha,/^[a-f0-9]{64}$/);
  assert.deepEqual((await publicExpensePhoto(slug,charge.id)).image,bytes);
  await manage("admin",slug,"hideExpensePhoto",{expenseId:charge.id});
  assert.equal(await publicExpensePhoto(slug,charge.id),undefined);
  assert.equal((await expenses(slug))[0].photo_hidden,1);
  assert.equal((await campaign(slug)).spent,25000);
  throw rollback;
}),error=>error===rollback);
assert.equal(await campaign("kiem-tra-trien-khai"),undefined);
console.log("Campaigns, private QR access, goods, impact, assistant, shifts, sessions and expenses verified without keeping test data.");
process.exit(0);
